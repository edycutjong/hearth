// Embeds worker/{worker.py,run.sh,requirements.txt} into src/lib/worker-source.ts, the copy the app injects
// into every Job (spec.injectedFiles, <= 64 KiB each). tests/worker-source.test.ts fails if they drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const files = { worker: "worker/worker.py", run: "worker/run.sh", requirements: "worker/requirements.txt" };
let out = "// GENERATED by scripts/embed-worker.mjs from worker/ — do not edit; run `npm run embed-worker`.\n\n";
for (const [name, rel] of Object.entries(files)) {
  const text = readFileSync(path.join(root, rel), "utf8");
  if (Buffer.byteLength(text) > 64 * 1024) throw new Error(`${rel} is over the 64 KiB injected-file limit`);
  out += `export const ${name.toUpperCase()}_SOURCE = ${JSON.stringify(text)};\n`;
  out += `export const ${name.toUpperCase()}_SHA256 = "${createHash("sha256").update(text).digest("hex")}";\n\n`;
}
writeFileSync(path.join(root, "src/lib/worker-source.ts"), out);
console.log("embedded", Object.values(files).join(", "));
